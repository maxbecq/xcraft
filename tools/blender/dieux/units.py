def sphinx(p):
    st, st2 = p["stone"], p["sand"]
    # a crouching lion of carved sandstone, low and powerful
    body(st, [(0, 0.45, 0.5), (0, 0.1, 0.52), (0, -0.25, 0.6), (0, -0.4, 0.78)], [(0, 1), (1, 2), (2, 3)],
         [(0.27, 0.25), (0.26, 0.24), (0.32, 0.3), 0.2])
    for s_ in (-1, 1):
        body(st, [(s_ * 0.2, -0.28, 0.5), (s_ * 0.24, -0.42, 0.26), (s_ * 0.24, -0.52, 0.08)], [(0, 1), (1, 2)], [0.15, 0.11, 0.1])
        body(st, [(s_ * 0.2, 0.45, 0.48), (s_ * 0.3, 0.38, 0.28), (s_ * 0.26, 0.5, 0.18), (s_ * 0.26, 0.36, 0.07)], [(0, 1), (1, 2), (2, 3)], [0.19, 0.14, 0.1, 0.1])
        for fy in (-0.6, 0.3):
            ball(st2, 0.11, (s_ * 0.25, fy, 0.06), (1, 1.3, 0.55))
            for t in (-1, 0, 1):
                ball(p["gold"], 0.018, (s_ * 0.25 + t * 0.05, fy - 0.13, 0.05))
        # wings: soft tapered feathers fanned along the back, gold tips, a rune glowing at the root
        for k in range(7):
            L = 0.85 - k * 0.07
            ang = math.radians(8 + k * 9)
            x = s_ * (0.2 + math.sin(ang) * L * 0.45)
            y = 0.0 + math.cos(ang) * L * 0.45
            ball(p["marble"], 0.5, (x, y, 0.9 + k * 0.015), (0.11 * 2, L, 0.05), (math.radians(-6), 0, -s_ * ang))
            ball(p["gold"], 0.5, (s_ * (0.2 + math.sin(ang) * L * 0.9), math.cos(ang) * L * 0.9, 0.92 + k * 0.015), (0.08 * 2, 0.16, 0.055), (0, 0, -s_ * ang))
        box(p["ether"], (0.02, 0.18, 0.05), (s_ * 0.3, -0.05, 0.62))
    strand(st, [(0, 0.68, 0.5), (0.12, 0.9, 0.35), (0.25, 1.0, 0.45), (0.3, 0.95, 0.62)], 0.045, 0.025)
    ball(p["gold"], 0.06, (0.3, 0.95, 0.65))
    # the face of the guardian, the striped headdress
    ball(st, 0.16, (0, -0.55, 0.98), (0.95, 1, 1.05))
    ball(p["lapis"], 0.21, (0, -0.48, 1.03), (1.15, 0.95, 1.0))
    for z in (0.92, 1.0, 1.08, 1.16):
        torus(p["gold"], 0.21 * math.sqrt(max(0.1, 1 - ((z - 1.03) / 0.21) ** 2)) + 0.004, 0.008, (0, -0.48, z))
    for s_ in (-1, 1):
        box(p["lapis"], (0.09, 0.07, 0.36), (s_ * 0.18, -0.53, 0.78))
        for z in (0.68, 0.78, 0.88):
            box(p["gold"], (0.095, 0.075, 0.025), (s_ * 0.18, -0.53, z))
        ball(p["ether"], 0.024, (s_ * 0.06, -0.7, 1.03))
    ball(st, 0.15, (0, -0.59, 0.96), (0.8, 0.9, 0.9))
    cyl(p["gold"], 0.05, 0.28, (0, -0.63, 0.78), v=8, r2=0.03)
    ball(p["sun"], 0.04, (0, -0.74, 0.9))
    ball(p["sun_veil"], 0.1, (0, -0.8, 0.9))
    cyl(p["gold"], 0.06, 0.12, (0, -0.44, 1.27), v=8, r2=0.0)
