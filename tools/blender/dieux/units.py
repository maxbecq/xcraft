def esprit(p):
    ball(p["ether_veil"], 0.17, (0, 0, 0.62), (1, 1, 1.35))
    ball(p["ether"], 0.07, (0, -0.02, 0.64))
    ball(p["gold"], 0.075, (0, -0.13, 0.7), (1, 0.4, 1.25))
    for x in (-0.028, 0.028):
        box(p["ether"], (0.03, 0.02, 0.012), (x, -0.165, 0.72))
    for k in range(3):
        pts = [(math.cos(k * 2.1 + t * 4) * 0.08 * (1 - t), 0.05 + 0.1 * t + math.sin(k * 2.1 + t * 4) * 0.08 * (1 - t), 0.5 - 0.42 * t) for t in (0, 0.25, 0.5, 0.75, 1)]
        strand(p["ether_soft"], pts, 0.04, 0.004)
    for s in (-1, 1):
        strand(p["ether_soft"], [(s * 0.12, 0, 0.66), (s * 0.22, -0.05, 0.58), (s * 0.24, -0.12, 0.62)], 0.025, 0.006)
    torus(p["gold"], 0.12, 0.008, (0, 0.02, 0.86), (0.4, 0, 0))
    motes(p["ether"], (0, 0, 0.3), 0.3, 8, 2, size=0.012, zmin=0.1, zmax=0.6)


